CREATE TABLE `t_order` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `customer_id` BIGINT NOT NULL COMMENT '顾客 id',
  `amount` DECIMAL(18,2) NOT NULL COMMENT '订单金额',
  `status` VARCHAR(16) NOT NULL DEFAULT 'PAID' COMMENT 'PAID/PENDING',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单';

CREATE TABLE `t_order_item` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `order_id` BIGINT NOT NULL COMMENT '订单 id',
  `sku` VARCHAR(32) NOT NULL COMMENT 'SKU',
  `qty` INT NOT NULL DEFAULT 1 COMMENT '数量',
  `price` DECIMAL(18,2) NOT NULL COMMENT '单价',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单明细';
